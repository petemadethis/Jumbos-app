def seed():
    """Seed the database with reference data."""
    init_db()
    db = SessionLocal()

    try:
        # Check if already seeded
        existing_states = db.query(State).count()
        if existing_states > 0:
            print(f"Database already has {existing_states} states. Skipping seed.")
            return

        # Insert states
        for code, name in US_STATES:
            db.add(State(code=code, name=name))
        db.flush()
        print(f"Seeded {len(US_STATES)} states.")

        # Insert cities and ZIP codes
        total_cities = 0
        total_zips = 0
        for state_code, city_name, zips in CITY_ZIPS:
            state = db.query(State).filter(State.code == state_code).first()
            if not state:
                continue
            slug = f"{city_name.lower().replace(' ', '-')}-{state_code.lower()}"
            city = City(name=city_name, state_code=state_code, slug=slug)
            db.add(city)
            db.flush()
            total_cities += 1

            for zip_code, lat, lng in zips:
                z = ZipCode(code=zip_code, city_id=city.id, latitude=lat, longitude=lng)
                db.add(z)
                total_zips += 1

        db.commit()
        print(f"Seeded {total_cities} cities and {total_zips} ZIP codes.")
        print("Seed complete!")

    except Exception as e:
        db.rollback()
        print(f"Error seeding database: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed()